package allbuild

import (
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"testing"
)

func generatedPushFunction(t *testing.T) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(rolloutRoot(t), "run.sh"))
	if err != nil {
		t.Fatal(err)
	}
	match := regexp.MustCompile(`(?ms)^git_push_generated_paths \(\) \(\n.*?^\)\n`).FindString(string(data))
	if match == "" {
		t.Fatal("missing generated config publisher")
	}
	return match
}

func TestGeneratedConfigPublicationPreservesSealedCheckout(t *testing.T) {
	for _, scenario := range []string{"disjoint", "lfs-disjoint", "same-path", "second-push-fails", "lost-response", "changed-after-publication"} {
		t.Run(scenario, func(t *testing.T) {
			dir := t.TempDir()
			remote, seed := filepath.Join(dir, "remote.git"), filepath.Join(dir, "seed")
			release, other := filepath.Join(dir, "release"), filepath.Join(dir, "other")
			runGit(t, dir, "init", "--bare", remote)
			runGit(t, dir, "init", "-b", "main", seed)
			if scenario == "lfs-disjoint" {
				runGit(t, seed, "lfs", "install", "--local")
				commitTestFile(t, seed, ".gitattributes", "generated filter=lfs diff=lfs merge=lfs -text\n", "LFS policy")
			}
			base := commitTestFile(t, seed, "base", "base\n", "base")
			runGit(t, seed, "remote", "add", "origin", remote)
			runGit(t, seed, "push", "-u", "origin", "main")
			runGit(t, dir, "--git-dir", remote, "symbolic-ref", "HEAD", "refs/heads/main")
			runGit(t, dir, "clone", remote, release)
			runGit(t, dir, "clone", remote, other)
			if scenario == "lfs-disjoint" {
				runGit(t, release, "lfs", "install", "--local")
			}
			generated := commitTestFile(t, release, "generated", "release bytes\n", "generated")
			remoteFile := "unrelated"
			if scenario == "same-path" {
				remoteFile = "generated"
			}
			concurrent := commitTestFile(t, other, remoteFile, "remote bytes\n", "concurrent")
			runGit(t, other, "push")
			if scenario == "lost-response" || scenario == "changed-after-publication" {
				runGit(t, release, "push", "origin", generated+":refs/heads/generated")
			}
			harness := `
set -u
eval "$1"
git() {
    if [[ "$1" = push ]]; then
        print push >> "$PUSH_EVENTS"
        local pushes=$(wc -l < "$PUSH_EVENTS" | tr -d ' ')
        if [[ "$SCENARIO" = second-push-fails && $pushes = 2 ]]; then return 43; fi
        if [[ "$SCENARIO" = lost-response && $pushes = 1 ]]; then
            command git push origin HEAD:refs/heads/main 2>/dev/null
            return 42
        fi
    fi
    command git "$@"
}
git_push_generated_paths generated
result=$?
exit $result
`
			// For lost-response, the remote already contains the exact commit.
			if scenario == "lost-response" || scenario == "changed-after-publication" {
				runGit(t, other, "fetch", "origin", "generated")
				runGit(t, other, "-c", "user.name=Test", "-c", "user.email=test@example.invalid", "merge", "--no-edit", generated)
			}
			if scenario == "changed-after-publication" {
				commitTestFile(t, other, "generated", "changed published bytes\n", "competing generated edit")
			}
			if scenario == "lost-response" || scenario == "changed-after-publication" {
				runGit(t, other, "push")
			}
			remoteBefore := runGit(t, other, "rev-parse", "HEAD")
			command := exec.Command("zsh", "-f", "-c", harness, "generated-push-test", generatedPushFunction(t))
			command.Dir = release
			events := filepath.Join(dir, "push-events")
			command.Env = append(os.Environ(), "PUSH_EVENTS="+events, "RELEASE_STATE_VERSION=sealed", "SCENARIO="+scenario, "GIT_AUTHOR_NAME=Test", "GIT_AUTHOR_EMAIL=test@example.invalid", "GIT_COMMITTER_NAME=Test", "GIT_COMMITTER_EMAIL=test@example.invalid")
			output, err := command.CombinedOutput()
			wantFailure := scenario == "same-path" || scenario == "second-push-fails" || scenario == "changed-after-publication"
			if (err != nil) != wantFailure {
				t.Fatalf("publication err=%v; output=%s", err, output)
			}
			if runGit(t, release, "rev-parse", "HEAD") != generated || runGit(t, release, "status", "--porcelain") != "" {
				t.Fatal("sealed checkout changed")
			}
			if bytes, err := os.ReadFile(filepath.Join(release, "generated")); err != nil || string(bytes) != "release bytes\n" {
				t.Fatal("generated bytes changed")
			}
			runGit(t, release, "fetch", "origin", "main")
			if wantFailure {
				if runGit(t, release, "rev-parse", "origin/main") != remoteBefore {
					t.Fatal("failed publication changed remote")
				}
			} else {
				runGit(t, release, "merge-base", "--is-ancestor", concurrent, "origin/main")
				runGit(t, release, "merge-base", "--is-ancestor", generated, "origin/main")
				if runGit(t, release, "show", "origin/main:unrelated") != "remote bytes" {
					t.Fatal("lost concurrent content")
				}
				if scenario == "lfs-disjoint" {
					consumer := filepath.Join(dir, "consumer")
					runGit(t, dir, "clone", remote, consumer)
					content, err := os.ReadFile(filepath.Join(consumer, "generated"))
					if err != nil || string(content) != "release bytes\n" {
						t.Fatalf("published LFS bytes missing: %v", err)
					}
				}
			}
			pushEvents, err := os.ReadFile(events)
			if err != nil {
				t.Fatal(err)
			}
			wantPushes := 2
			if scenario == "same-path" || scenario == "lost-response" || scenario == "changed-after-publication" {
				wantPushes = 1
			}
			if len(pushEvents) != len("push\n")*wantPushes {
				t.Fatalf("push attempts = %q", pushEvents)
			}
			if base == generated {
				t.Fatal("fixture did not create generated commit")
			}
		})
	}
}
